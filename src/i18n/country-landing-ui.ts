// Swiss Standard German: no "ß".
function swiss<T>(v: T): T {
  if (typeof v === 'string') return v.replace(/ß/g, 'ss') as unknown as T;
  if (Array.isArray(v)) return v.map((x) => swiss(x)) as unknown as T;
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, swiss(x)])) as T;
  return v;
}
