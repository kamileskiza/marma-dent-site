export function treatmentSlug(locale: string, id: TreatmentId): string {
  return SLUGS[locale]?.[id] ?? SLUGS.en[id]!;
}

// Reverse lookup: given a locale + slug from the URL, find which treatment it is.
export function treatmentIdFromSlug(locale: string, slug: string): TreatmentId | null {
  const table = SLUGS[locale] ?? SLUGS.en;
  for (const id of TREATMENT_IDS) {
    if ((table[id] ?? SLUGS.en[id]) === slug) return id;
  }
  return null;
}
